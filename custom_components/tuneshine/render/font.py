@dataclass(frozen=True)
class Glyph:
    """A single bitmap glyph."""

    width: int
    rows: tuple[str, ...]


@dataclass
class PixelFont:
    """A proportional bitmap font."""

    source: dict[str, str]
    height: int
    line_height: int
    spacing: int = 1
    upper_only: bool = False
    _glyphs: dict[str, Glyph] = field(default_factory=dict, init=False, repr=False)

    def __post_init__(self) -> None:
        for char, spec in self.source.items():
            rows = tuple(spec.split(" "))
            self._glyphs[char] = Glyph(len(rows[0]), rows)

    def glyph(self, char: str) -> Glyph:
        """Return the glyph for a character, falling back sensibly."""
        if self.upper_only:
            char = char.upper()
        if char in self._glyphs:
            return self._glyphs[char]
        if char.upper() in self._glyphs:
            return self._glyphs[char.upper()]
        return self._glyphs["?"]

    def text_width(self, text: str, scale_x: int = 1, bold: bool = False) -> int:
        """Width in pixels of text drawn at the given horizontal scale."""
        if not text:
            return 0
        extra = 1 if bold else 0
        widths = [self.glyph(c).width * scale_x + extra for c in text]
        return sum(widths) + self.spacing * scale_x * (len(text) - 1)

    def text_height(self, scale_y: int = 1) -> int:
        """Height of a line at the given vertical scale, ignoring descenders."""
        return self.height * scale_y

    def draw(
        self,
        draw: ImageDraw.ImageDraw,
        xy: tuple[int, int],
        text: str,
        fill: Color | int,
        scale: tuple[int, int] = (1, 1),
        bold: bool = False,
    ) -> int:
        """Draw text with its top-left at xy. Returns the x after the last glyph.

        Bold smears every lit pixel one pixel to the right, which thickens
        vertical strokes without changing the glyph shapes.
        """
        x, y = xy
        sx, sy = scale
        extra = 1 if bold else 0
        for char in text:
            glyph = self.glyph(char)
            for row_index, row in enumerate(glyph.rows):
                for col_index, pixel in enumerate(row):
                    if pixel != "#":
                        continue
                    px = x + col_index * sx
                    py = y + row_index * sy
                    # Don't smear into a one-pixel gap (m, w, M, W...) or it fills in.
                    smear = extra and not (
                        col_index + 2 < len(row)
                        and row[col_index + 1] == "."
                        and row[col_index + 2] == "#"
                    )
                    draw.rectangle((px, py, px + sx - 1 + smear, py + sy - 1), fill=fill)
            x += (glyph.width + self.spacing) * sx + extra
        return x - self.spacing * sx

    def mask(self, text: str, scale: tuple[int, int] = (1, 1), bold: bool = False) -> Image.Image:
        """An 'L' mask of the text, tall enough for descenders."""
        width = max(self.text_width(text, scale[0], bold), 1)
        height = (self.height + 1) * scale[1]
        image = Image.new("L", (width, height), 0)
        self.draw(ImageDraw.Draw(image), (0, 0), text, 255, scale, bold)
        return image


